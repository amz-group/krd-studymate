function esc(s) {
  return String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
const p = (t) => `<p>${esc(t)}</p>`;
const h = (id, t) => `<h2 data-rd-id="sec-${id}">${esc(t)}</h2>`;
const ul = (items) => `<ul>${items.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>`;
const fig = (n, cap) => `<div class="rd-fig" style="text-align:center;" data-rd-fig="${n}"><img src="${PLACEHOLDER_IMG}" style="width:70%;border-radius:6px;" alt="figure"><p class="rd-caption">Figure ${n}: ${esc(cap)}</p></div>`;
const table = (headers, rows) => {
  const th = headers.map((x) => `<th style="border:1px solid #cbd5e1;padding:8px;text-align:left;background:#e2e8f0;">${esc(x)}</th>`).join('');
  const trs = rows.map((r) => `<tr>${r.map((c) => `<td style="border:1px solid #cbd5e1;padding:8px;">${esc(c)}</td>`).join('')}</tr>`).join('');
  return `<table style="border-collapse:collapse;width:100%;"><thead><tr>${th}</tr></thead><tbody>${trs}</tbody></table>`;
};
const code = (src) => `<pre style="background:#0f172a;color:#e2e8f0;padding:12px;border-radius:8px;overflow:auto;font-family:ui-monospace,monospace;font-size:13px;">${esc(src)}</pre>`;
const refsBlock = () => '<div class="rd-refs" data-rd-refs="1"></div>';
const toc = () => '<div class="rd-toc" data-toc="1"></div>';

