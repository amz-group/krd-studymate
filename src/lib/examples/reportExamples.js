export function buildReportExampleProject(example) {
  const tpl = getTemplate(example.template);
  const proj = createReportProject({
    title: example.name,
    subtitle: '',
    category: 'report',
    language: example.language,
    templateId: example.template,
    blank: true,
    studentInfo: { title: example.name, students: [{ name: '', id: '' }], university: '' },
  });
  proj.content.html = example.build();
  proj.content.references = { ...proj.content.references, items: example.refs || [] };
  proj.content.cover = { ...proj.content.cover, layout: example.coverLayout || 'classic', primaryColor: tpl.colors.primary, fontFamily: tpl.fonts.heading };
  proj.content.template = example.template;
  proj.content.fontFamily = tpl.fonts.body;
  return proj;
}

